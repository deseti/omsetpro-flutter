class QuickStatsCard extends StatelessWidget {
  final String title;
  final List<QuickStatItem> items;

  const QuickStatsCard({
    super.key,
    required this.title,
    required this.items,
  });

  @override
  Widget build(BuildContext context) {
    return Card(
      elevation: 2,
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular(12),
      ),
      child: Padding(
        padding: const EdgeInsets.all(16),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Text(
              title,
              style: const TextStyle(
                fontSize: 16,
                fontWeight: FontWeight.bold,
                color: Colors.black87,
              ),
            ),
            const SizedBox(height: 16),
            ...items.map((item) => _buildStatItem(item)),
          ],
        ),
      ),
    );
  }

  Widget _buildStatItem(QuickStatItem item) {
    return Padding(
      padding: const EdgeInsets.only(bottom: 12),
      child: Row(
        children: [
          Container(
            width: 8,
            height: 8,
            decoration: BoxDecoration(
              color: item.color,
              shape: BoxShape.circle,
            ),
          ),
          const SizedBox(width: 12),
          Expanded(
            child: Text(
              item.label,
              style: TextStyle(
                fontSize: 14,
                color: Colors.grey[700],
              ),
            ),
          ),
          Text(
            item.value,
            style: const TextStyle(
              fontSize: 14,
              fontWeight: FontWeight.w600,
              color: Colors.black87,
            ),
          ),
        ],
      ),
    );
  }
}

class QuickStatItem {
  final String label;
  final String value;
  final Color color;

  QuickStatItem({
    required this.label,
    required this.value,
    required this.color,
  });
}

// Helper untuk format currency
class CurrencyFormatter {
  static final _formatter = NumberFormat.currency(
    locale: 'id_ID',
    symbol: 'Rp ',
    decimalDigits: 0,
  );

  static String format(double amount) {
    return _formatter.format(amount);
  }
}

// Helper untuk format number
class NumberFormatter {
  static String format(int number) {
    return NumberFormat('#,##0', 'id_ID').format(number);
  }

  static String formatDouble(double number, {int decimalDigits = 1}) {
    return NumberFormat('#,##0.${'0' * decimalDigits}', 'id_ID').format(number);
  }
}
